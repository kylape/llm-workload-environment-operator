#!/usr/bin/env python3
"""Package canonical CRD/ClusterRole manifests into the operator chart."""

import argparse
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
FILES = ROOT / "charts/llm-workload-environment-operator/files"


def generated_manifests():
    roles = []
    for path in sorted((ROOT / "config/rbac").glob("*.yaml")):
        text = path.read_text()
        if re.search(r"^kind: ClusterRole$", text, re.MULTILINE):
            roles.append(text.removeprefix("---\n").rstrip())
    if not roles:
        raise RuntimeError("No canonical ClusterRoles found")
    return {
        FILES / "llmworkloadenvironments.yaml":
            (ROOT / "config/crd/bases/llm.redhat.com_llmworkloadenvironments.yaml").read_bytes(),
        FILES / "clusterroles.yaml":
            ("# Generated by tools/sync-chart-manifests.py; edit config/rbac instead.\n"
             + "---\n" + "\n---\n".join(roles) + "\n").encode(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if packaged manifests are stale")
    args = parser.parse_args()
    stale = []
    for path, content in generated_manifests().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            print(f"Updated {path.relative_to(ROOT)}")
    if stale:
        print("Stale chart assets; run make generate-chart:\n" + "\n".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
